/** Exposed for the key-parity test; the app itself only uses the i18n instance. */
export const translations = { en, bn }

function initialLanguage(): 'bn' | 'en' {
  if (typeof window === 'undefined') return 'bn'
  try {
    return window.localStorage.getItem('pc.lang') === 'en' ? 'en' : 'bn'
  } catch {
    return 'bn'
  }
}

void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: translations.en },
    bn: { translation: translations.bn },
  },
  lng: initialLanguage(),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
  returnNull: false,
})

if (typeof document !== 'undefined') {
  document.documentElement.lang = i18n.language
}

export default i18n
